def nest(idx):
    root = {}
    for k, v in M.items():
        parts = k.split(".")
        cur = root
        for p in parts[:-1]:
            nxt = cur.setdefault(p, {})
            if not isinstance(nxt, dict):
                raise SystemExit(f"key conflict at {k}")
            cur = nxt
        if parts[-1] in cur and isinstance(cur[parts[-1]], dict):
            raise SystemExit(f"key conflict at {k}")
        cur[parts[-1]] = v[idx]
    return root

